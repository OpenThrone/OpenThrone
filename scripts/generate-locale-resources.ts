/**
 * Generates src/lib/localeResources.ts from public/locales/**.json.
 *
 * Server-side translation loading on Cloudflare Workers cannot read locale
 * files from disk (next-i18next's fs-backend), so the server wrapper
 * (src/utils/serverTranslations.ts) preloads every locale/namespace from the
 * generated module instead. The file is committed; rerun this script (or any
 * `cloudflare:*` script, which regenerates it) whenever locale JSON changes.
 *
 * Run: bun run locales:generate
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const LOCALES_DIR = path.join(process.cwd(), 'public', 'locales');
const OUTPUT = path.join(process.cwd(), 'src', 'lib', 'localeResources.ts');

const locales = readdirSync(LOCALES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const namespacesByLocale = new Map<string, string[]>();
for (const locale of locales) {
  const namespaces = readdirSync(path.join(LOCALES_DIR, locale))
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
  namespacesByLocale.set(locale, namespaces);
}

// All locales must expose the same namespace set, otherwise the preload would
// silently miss namespaces for one language and fall back mid-render.
const referenceNamespaces = namespacesByLocale.get(locales[0]) ?? [];
for (const [locale, namespaces] of namespacesByLocale) {
  const missing = referenceNamespaces.filter((ns) => !namespaces.includes(ns));
  if (missing.length > 0) {
    console.error(
      `locale '${locale}' is missing namespaces present in '${locales[0]}': ${missing.join(', ')}`,
    );
    process.exit(1);
  }
}

// Validate JSON while we are here — a broken file should fail the build, not
// first render at runtime.
for (const [locale, namespaces] of namespacesByLocale) {
  for (const ns of namespaces) {
    try {
      JSON.parse(
        readFileSync(path.join(LOCALES_DIR, locale, `${ns}.json`), 'utf8'),
      );
    } catch (error) {
      console.error(`invalid JSON in ${locale}/${ns}.json: ${error}`);
      process.exit(1);
    }
  }
}

// Namespace names contain hyphens (e.g. admin-abuse), which are not valid in
// import identifiers — map them onto underscored names. The exported object
// still uses the real hyphenated namespace keys.
const importName = (locale: string, ns: string) =>
  `${locale}__${ns.replace(/-/g, '_')}`;

let out = `// AUTO-GENERATED by scripts/generate-locale-resources.ts — do not edit.
// Source: public/locales/**.json. Regenerate with: bun run locales:generate

`;

for (const [locale, namespaces] of [...namespacesByLocale.entries()].sort()) {
  for (const ns of namespaces) {
    out += `import ${importName(locale, ns)} from '../../public/locales/${locale}/${ns}.json';\n`;
  }
}

out += `
/**
 * Every locale/namespace bundled for server-side rendering. Preloading these
 * through the next-i18next config keeps the fs-backend from ever reading
 * public/locales at request time, which cannot work on Cloudflare Workers.
 */
export const localeResources: Record<string, Record<string, object>> = {
`;

for (const [locale, namespaces] of [...namespacesByLocale.entries()].sort()) {
  out += `  ${locale}: {\n`;
  for (const ns of namespaces) {
    out += `    '${ns}': ${importName(locale, ns)},\n`;
  }
  out += `  },\n`;
}
out += `};\n`;

writeFileSync(OUTPUT, out);
console.log(
  `wrote ${path.relative(process.cwd(), OUTPUT)} (${locales.length} locales x ${referenceNamespaces.length} namespaces)`,
);
