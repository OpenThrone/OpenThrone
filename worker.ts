/**
 * Custom Cloudflare Worker entry for OpenThrone.
 *
 * Re-exports the OpenNext (Next.js) handler produced by `bun run
 * cloudflare:build` into `.open-next/worker.js` and adds the `scheduled()`
 * entry point for Cloudflare Cron Triggers. The scheduled handler fans out to
 * the existing HTTP cron endpoints through the WORKER_SELF_REFERENCE service
 * binding — no public network involved — using the raw TASK_SECRET
 * Authorization header contract documented in docs/operations.md. Each
 * endpoint keeps its enable flag (DO_TURN_UPDATES etc.) and its own
 * guards/idempotency (per-user row locks, see
 * src/services/__tests__/cronJob.concurrency.test.ts).
 *
 * The dispatch itself lives in src/lib/workerCron.ts (injectable fetch/env/
 * cron event, per-endpoint results, unit-tested there); this entry only
 * delegates, keeping the external behavior identical.
 */

// Generated by `bun run cloudflare:build`; absent during pure Node type
// checks, hence the suppressed import error. The .js extension is required —
// the file on disk is worker.js.
// @ts-expect-error - no declaration for the generated worker bundle
// eslint-disable-next-line import/extensions -- generated file is .js
import openNextWorker from './.open-next/worker.js';
// hash-wasm's argon2 (password + API-token hashing) also compiles embedded
// wasm at runtime, which workerd forbids — inject it the same way. The
// generated patch in hash-wasm seeds its per-algorithm module cache from
// this map; Node/Bun runtimes never set it and behave as before.
// @ts-expect-error - wasm module binding emitted by wrangler
// eslint-disable-next-line import/extensions -- wrangler wasm module import
import argon2Wasm from './prisma-generated/argon2.wasm';
// hash-wasm's argon2 loads a companion blake2b module at runtime (the
// algorithm's initial Blake2b-512 hash) — inject both or the blake2b half
// still compiles base64 bytes at runtime on workerd.
// @ts-expect-error - wasm module binding emitted by wrangler
// eslint-disable-next-line import/extensions -- wrangler wasm module import
import blake2bWasm from './prisma-generated/blake2b.wasm';
// The Prisma query compiler must ship as a build-time wasm module binding:
// workerd forbids compiling wasm bytes at runtime, which is how the generated
// client loads it by default. scripts/extract-prisma-wasm.ts writes the file
// (chained into cloudflare:build) and scripts/patch-prisma-wasm.ts makes the
// generated client consume this injection. Plain Node/Bun runtimes never set
// the global and keep their original loader.
// @ts-expect-error - wasm module binding emitted by wrangler
// eslint-disable-next-line import/extensions -- wrangler wasm module import
import prismaQueryCompilerWasm from './prisma-generated/query_compiler.postgresql.wasm';
// Durable Objects realtime pilot (#23): the ChatRoomDO class (re-exported
// below for wrangler's durable_objects binding) and the /do/* router that
// dispatches chat-room and user-mailbox requests to it. Relative imports with
// no @/ aliases — same wrangler esbuild constraint as workerCron above.
import { ChatRoomDO } from './src/durable-objects/ChatRoomDO';
// Cron Trigger fan-out (mapping table, sequential dispatch, raw TASK_SECRET
// header, no-retry/no-deduplicate boundary contract). Zero-import module so
// the wrangler esbuild bundle needs no path aliases.
// Builds the Prisma client and query compiler at isolate startup instead of
// in the first request (src/lib/prismaClients.ts).
import { warmWorkerPrismaClient } from './src/lib/prismaClients';
import {
  dispatchScheduledCron,
  type ExecutionContextLike,
  type ScheduledControllerLike,
  type WorkerCronEnv,
} from './src/lib/workerCron';
import {
  type DoWorkerEnv,
  routeDurableObjectRequest,
} from './src/lib/workerDoRouter';
import {
  handleRehearsalRequest,
  type RehearsalEnv,
  withNoIndex,
} from './src/lib/workerRehearsal';

(
  globalThis as unknown as {
    __OT_PRISMA_QUERY_COMPILER_WASM__?: WebAssembly.Module;
  }
).__OT_PRISMA_QUERY_COMPILER_WASM__ = prismaQueryCompilerWasm;

(
  globalThis as unknown as {
    __OT_HASH_WASM_MODULES__?: Record<string, WebAssembly.Module>;
  }
).__OT_HASH_WASM_MODULES__ = { argon2: argon2Wasm, blake2b: blake2bWasm };

// After the wasm globals above: the generated client reads the injected
// query-compiler module when it connects.
warmWorkerPrismaClient().catch(() => undefined);

const worker = {
  ...openNextWorker,
  async fetch(
    request: Request,
    env: WorkerCronEnv & DoWorkerEnv & RehearsalEnv,
    ctx: ExecutionContextLike,
  ): Promise<Response> {
    // /do/chat/<roomId> and /do/user/<userId> go to the ChatRoomDO namespace
    // (see src/lib/workerDoRouter.ts); null means "not a DO request" and the
    // request continues into the OpenNext handler unchanged.
    const rehearsalResponse = await handleRehearsalRequest(request, env);
    if (rehearsalResponse) return rehearsalResponse;
    const doResponse = await routeDurableObjectRequest(request, env);
    if (doResponse) return doResponse;
    return withNoIndex(await openNextWorker.fetch(request, env, ctx), env);
  },
  async scheduled(
    controller: ScheduledControllerLike,
    env: WorkerCronEnv,
    ctx: ExecutionContextLike,
  ): Promise<void> {
    dispatchScheduledCron(controller, env, ctx);
  },
};

export default worker;

// Durable Object class for the realtime pilot; wrangler.jsonc binds it as
// CHAT_ROOM_DO (durable_objects.bindings + migrations.new_sqlite_classes).
export { ChatRoomDO };
