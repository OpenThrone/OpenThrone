export type PseudonymRandom = Pick<typeof crypto, 'randomInt'>;

/** Generates an inoffensive fantasy pseudonym using cryptographic randomness. */
export function generatePseudonym(random: PseudonymRandom = crypto): string {
  return `${ADJECTIVES[random.randomInt(ADJECTIVES.length)]}_${NOUNS[random.randomInt(NOUNS.length)]}_${random.randomInt(10000, 100000)}`;
}

/** Retries collisions; callers must still enforce uniqueness at write time. */
export async function generateUniquePseudonym(
  isTaken: (name: string) => Promise<boolean>,
  maxAttempts = 10,
): Promise<string> {
  if (!Number.isSafeInteger(maxAttempts) || maxAttempts < 1) {
    throw new Error('maxAttempts must be a positive integer');
  }
  for (let attempt = 0; attempt < maxAttempts; attempt += 1) {
    const name = generatePseudonym();
    if (!(await isTaken(name))) return name;
  }
  throw new Error('Unable to generate a unique pseudonym');
}
